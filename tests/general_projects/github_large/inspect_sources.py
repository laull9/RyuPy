#!/usr/bin/env python3
"""固定上游提交的只读源码盘点：分类 LOC、AST 特性、静态导入图与入口闭包。

不导入上游、不写 pyc、不生成业务替身；仅 --prepare 联网克隆。缓存复用时验证 Git
提交定位与工作树状态，不计算文件摘要。完整图可输出到仓库外，用后由调用者清理。
"""
import argparse
import ast
from collections import Counter
import json
from pathlib import Path
import re
import subprocess
import sys
import tokenize

CATALOG = Path(__file__).with_name('catalog.json')
CACHE = Path.home() / '.cache/ryupy/upstream-projects'
REPO = Path(__file__).resolve().parents[3]


def git(path, *args):
    """Git 只承担版本定位和跟踪文件枚举。"""
    return subprocess.check_output(['git', '-C', str(path), *args], text=True).strip()


def prepare(project, cache):
    """新建专用 clone；已有缓存只读复用，脏目录或版本变化直接停止。"""
    path = cache / project['repo'].replace('/', '--')
    if not path.exists():
        subprocess.run(['git', 'clone', '--no-checkout', '--depth', '1',
                        'https://github.com/' + project['repo'] + '.git', str(path)], check=True)
        subprocess.run(['git', '-C', str(path), 'fetch', '--depth', '1', 'origin',
                        project['commit']], check=True)
        subprocess.run(['git', '-C', str(path), 'checkout', '--detach',
                        project['commit']], check=True)
    return path


def category(name, text):
    """测试优先分列；UI 布局保守剔除，避免把生成/手修 Designer 代码计为业务。

    Ui_* + setupUi 也可能手写，所以分类明确称 UI 布局候选，不声称全是自动生成。
    Alembic 自动迁移保留在源码项，它属于待验业务合同。
    """
    path = Path(name)
    if any(p in ('tests', 'test') for p in path.parts) or path.name.startswith('test_') or path.name == 'conftest.py':
        return 'tests'
    header = text[:3000]
    if ('Resource object code' in header or re.search(
            r'(pyside6-[ur]cc|pyside6-uic|form implementation generated)', header, re.I)):
        return 'generated_ui_resource'
    if ('run again.  Do not edit this file' in header
            or (re.search(r'class Ui_\w+', text) and 'def setupUi(' in text)):
        return 'ui_layout_candidate'
    return 'source'


def module_name(name, root):
    parts = list(Path(name).relative_to(root).with_suffix('').parts)
    if parts[-1] == '__init__':
        parts.pop()
    return '.'.join(parts)


def analyze(project, path):
    """用标准库 AST 解析所有跟踪 Python 文件，导入边带源码位置且保留未解析项。"""
    if git(path, 'rev-parse', 'HEAD') != project['commit']:
        raise ValueError(f'{path}: 固定提交不匹配')
    if git(path, 'status', '--porcelain', '--untracked-files=normal'):
        raise ValueError(f'{path}: 缓存有修改，请另行保留后重建，驱动不会清理它')
    names = git(path, 'ls-files', '*.py').splitlines()
    modules = {}
    for name in names:
        for root in project['import_roots']:
            try:
                module = module_name(name, root)
            except ValueError:
                continue
            if module:
                modules.setdefault(module, name)
    counts = {k: {'files': 0, 'loc': 0} for k in
              ('source', 'tests', 'generated_ui_resource', 'ui_layout_candidate')}
    features = Counter()
    edges, external, dynamic, failures = [], [], [], []
    classifications = {}
    for name in names:
        with tokenize.open(path / name) as stream:
            text = stream.read()
        kind = category(name, text)
        classifications[name] = kind
        counts[kind]['files'] += 1
        counts[kind]['loc'] += len(text.splitlines())
        try:
            tree = ast.parse(text, filename=name)
        except SyntaxError as exc:
            failures.append({'file': name, 'line': exc.lineno, 'error': exc.msg})
            continue
        # 文件可有多个 import root 别名；相对导入按最长匹配模块解释。
        aliases = [m for m, f in modules.items() if f == name]
        current = max(aliases, key=len, default='')
        package = current if name.endswith('/__init__.py') else current.rpartition('.')[0]
        for node in ast.walk(tree):
            features[type(node).__name__] += 1
            if isinstance(node, (ast.Import, ast.ImportFrom)):
                if isinstance(node, ast.Import):
                    targets = [a.name for a in node.names]
                else:
                    prefix = node.module or ''
                    if node.level:
                        parent = package.split('.')
                        parent = parent[:len(parent) - node.level + 1]
                        prefix = '.'.join([*parent, prefix]).strip('.')
                    targets = [prefix, *(prefix + '.' + a.name for a in node.names)]
                for target in sorted(set(targets)):
                    resolved = target
                    while resolved and resolved not in modules:
                        resolved = resolved.rpartition('.')[0]
                    item = {'file': name, 'line': node.lineno, 'module': target}
                    if resolved:
                        edges.append(dict(item, target=modules[resolved]))
                    elif target:
                        external.append(item)
            if isinstance(node, ast.Call):
                function = ast.unparse(node.func)
                if function.endswith(('import_module', '__import__', 'exec', 'eval')):
                    dynamic.append({'file': name, 'line': node.lineno, 'call': function})
    graph = {}
    for edge in edges:
        graph.setdefault(edge['file'], set()).add(edge['target'])
    reached, pending = set(), [project['entry']]
    while pending:
        name = pending.pop()
        if name not in reached:
            reached.add(name)
            pending.extend(graph.get(name, ()))
    return {
        'id': project['id'], 'commit': project['commit'], 'python': sys.version.split()[0],
        'counts': counts, 'features': features, 'parse_failures': failures,
        'static_local_edges': len({(e['file'], e['target']) for e in edges}),
        'entry_static_files': len(reached), 'entry_static_closure': sorted(reached),
        'dynamic_sites': dynamic, 'edges': edges, 'external_or_unresolved': external,
        'classifications': classifications,
        'graph_limit': '仅语法导入超图，含条件/TYPE_CHECKING/函数内导入；动态导入需运行追踪',
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--prepare', action='store_true')
    parser.add_argument('--all-candidates', action='store_true')
    parser.add_argument('--cache', type=Path, default=CACHE)
    parser.add_argument('--output', type=Path, help='可选完整图 JSON，必须写仓库外')
    args = parser.parse_args()
    cache = args.cache.expanduser().resolve()
    if cache.is_relative_to(REPO):
        parser.error('缓存必须放仓库外')
    if args.output and args.output.resolve().is_relative_to(REPO):
        parser.error('分析产物必须放仓库外')
    if sys.version_info[:3] != (3, 12, 13):
        parser.error('请使用固定 CPython 3.12.13；其它语法版本另开分析门')
    cache.mkdir(parents=True, exist_ok=True)
    results = []
    for project in json.loads(CATALOG.read_text())['projects']:
        if not project['selected'] and not args.all_candidates:
            continue
        path = prepare(project, cache) if args.prepare else cache / project['repo'].replace('/', '--')
        result = analyze(project, path)
        results.append(result)
        print(json.dumps({k: result[k] for k in ('id', 'commit', 'counts', 'parse_failures',
                         'static_local_edges', 'entry_static_files')}, ensure_ascii=False))
    if args.output:
        args.output.write_text(json.dumps(results, ensure_ascii=False, indent=2) + '\n')


if __name__ == '__main__':
    main()
